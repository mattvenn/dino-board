#!/usr/bin/env python3
"""Flatten KiCad's netlist (build/sch/netlist.net) into text a reviewer can read: parts, then nets."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
text = open(os.path.join(ROOT, 'build', 'sch', 'netlist.net'), encoding='utf-8').read()
key = lambda r: (re.sub(r'\d+$', '', r), int(re.search(r'\d+$', r).group()) if re.search(r'\d+$', r) else 0)
comps = re.findall(r'\(comp\s*\(ref "([^"]+)"\)\s*\(value "([^"]*)"\)\s*\(footprint "([^"]*)"\)', text)
out = ['DinoLight flattened netlist, from the schematic as generated by tools/schematic.py', '', 'PARTS: ref | value | footprint']
out += ['%s | %s | %s' % c for c in sorted(comps, key=lambda c: key(c[0]))]
out += ['', 'NETS: NET: REF.PIN(pin name) ...']
for m in re.finditer(r'\(net\s*\(code "?\d+"?\)\s*\(name "([^"]*)"\)(.*?)(?=\(net\s*\(code|\Z)', text, re.S):
    nodes = re.findall(r'\(node\s*\(ref "([^"]+)"\)\s*\(pin "([^"]+)"\)(?:\s*\(pinfunction "([^"]*)"\))?', m.group(2))
    nodes.sort(key=lambda n: key(n[0]))
    out.append('%s: %s' % (m.group(1), ' '.join('%s.%s(%s)' % n for n in nodes)))
open(os.path.join(ROOT, 'build', 'sch', 'netlist_flat.txt'), 'w').write('\n'.join(out) + '\n')
print(len(comps), 'parts,', len(out) - len(comps) - 4, 'nets')
